/** Detect the active UI language from a probe translation. */
export function detectLanguage(probeText) {
  return /[\u3400-\u9fff]/.test(String(probeText || '')) ? 'zh' : 'en'
}

/** Replace `{name}` placeholders in one template. */
export function interpolate(template, params) {
  if (!params) return template
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (params[name] == null ? match : String(params[name])))
}
